#!/usr/bin/env bash
# Generate app/pin-manifest.txt: the files one first agent turn reads, in the
# order they are first opened. Traced with strace inside the built image (the
# list depends on the base image and the DSH version, so never write it by
# hand), by running the real wrapper and sending it one agent turn.
#
# Run after build_image.sh, then build again so the image carries the manifest.
set -euo pipefail
cd "$(dirname "$0")/.."

DSH_VERSION="${DSH_VERSION:-0.2.2-rc.1}"
IMAGE="${IMAGE:-dsh-coldstart}:${TAG:-dsh-${DSH_VERSION}-pin}"
REGION="${REGION:-us-east-1}"
OUT=app/pin-manifest.txt
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
chmod 777 "$WORK"

# Credentials reach the container as environment variables and are never printed.
eval "$(aws configure export-credentials --format env)"
docker run --rm --platform linux/arm64 --user root -v "$WORK:/trace" \
    -e AWS_ACCESS_KEY_ID -e AWS_SECRET_ACCESS_KEY -e AWS_SESSION_TOKEN -e "AWS_REGION=${REGION}" \
    -e DSH_PREWARM=0 -e HOST=127.0.0.1 --entrypoint bash "$IMAGE" -c '
set -e
apt-get update -qq >/dev/null && apt-get install -y -qq --no-install-recommends strace >/dev/null
runuser -u node -- strace -f -qq -e trace=openat,execve -o /trace/strace.txt node /opt/dsh/server.mjs >/trace/server.log 2>&1 &
runuser -u node -- node -e "
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  for (let i = 0; i < 120; i++) {
    try { if ((await fetch(\"http://127.0.0.1:8080/ping\")).ok) break; } catch {}
    await sleep(250);
  }
  const res = await fetch(\"http://127.0.0.1:8080/invocations\", { method: \"POST\",
    body: JSON.stringify({ mode: \"agent\", prompt: \"Reply with exactly: pong\" }) });
  const body = await res.json();
  console.log(\"traced turn ok=\" + body.agent.ok + \" output=\" + JSON.stringify(body.agent.output));
  process.exit(body.agent.ok ? 0 : 1);
})();"
# Resolve every successfully opened or executed path to a regular file inside
# the image, keep first-open order, and drop duplicates by inode.
python3 - <<PY
import os, re
seen, out, total = set(), [], 0
pat = re.compile(r"(?:openat\(AT_FDCWD, |execve\()\"([^\"]+)\".*= (\d+)$")
skip = ("/proc/", "/sys/", "/dev/", "/tmp/", "/trace/", "/workspace/", "/home/node/.dsh/", "/run/")
for line in open("/trace/strace.txt", errors="replace"):
    m = pat.search(line)
    if not m or "O_DIRECTORY" in line or "O_WRONLY" in line or "O_RDWR" in line:
        continue
    path = os.path.realpath(m.group(1))
    if not path.startswith("/") or path.startswith(skip) or not os.path.isfile(path):
        continue
    st = os.stat(path)
    if st.st_size == 0 or (st.st_dev, st.st_ino) in seen:
        continue
    seen.add((st.st_dev, st.st_ino))
    out.append(path)
    total += st.st_size
with open("/trace/manifest.txt", "w") as f:
    f.write("# generated by scripts/gen_pin_manifest.sh; %d files, %d bytes\n" % (len(out), total))
    f.write("\n".join(out) + "\n")
print("manifest: %d files, %.1f MB" % (len(out), total / 2**20))
PY
chmod a+r /trace/manifest.txt'
cp "$WORK/manifest.txt" "$OUT"
echo "Wrote $OUT ($(grep -vc '^#' "$OUT") files). Rebuild the image to include it."
